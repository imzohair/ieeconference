<h4 class="text-dark m-4">Submission to the CMT Portal</h4>
            

<div class="about-text-center">
    <p class="text-justify">Follow the steps below to prepare and submit the final camera-ready paper and copyright form.</p>
    
    <h4 class="text-dark text-justify">Step 1: Prepare the Final Camera-Ready Paper</h4>
    <p class="text-justify">Prepare the final camera-ready paper after considering all the requirements above and incorporating the reviewer comments.</p>
    
    <h4 class="text-dark text-justify">Step 2: Insert the IEEE Copyright Notice</h4>
    <p class="text-justify">Place the appropriate copyright notice at the bottom of the first page of each paper. Replace the copyright notice in the camera-ready version with one of the following notices, as applicable:</p>
    
