<h4 class="text-dark m-4">Additional Camera-Ready Formatting Requirements</h4>
            

<div class="about-text-center">
     
         
           <!--list-->
            <ul>
             <li>Use Times New Roman throughout the manuscript, paying particular attention to paragraph formatting from the Abstract through the References section.</li>
<li>Set the paper title in 24-point regular font; it should not be bold or italicized.</li>
<li>Use 9-point regular font for author names. Do not use salutations such as Dr., Mr., Mrs., Prof., Research Scholar, or Student.</li>
<li>Format the word “Abstract” in 9-point bold italic font. Format the abstract text in 9-point bold, non-italic font.</li>
<li>Format “Keywords” in 9-point bold italic font, with keywords separated by commas.</li>
<li>Use 10-point regular font for main headings, with the first letter capitalized and the headings centred. Precede headings with Roman numerals.</li>
<li>Ensure that every in-text citation has a corresponding entry in the References section and vice versa.</li>
<li>Arrange citations in ascending numerical order rather than in random order.</li>
<li>Do not cite references in the Abstract or Conclusion sections.</li>
<li>Avoid the use of first-person expressions such as “our,” “we,” and “us.”</li>
<li>Use 10-point italic font for subheadings and align them to the left. Label subheadings using capital letters such as A, B, and so on.</li>
<li>Use subsequent levels such as 1), 2), and further levels such as a), b), with appropriate indentation.</li>
<li>Use “Fig.” rather than “Figure.” Figure numbers and captions must be in 8-point regular font and properly justified.</li>
<li>Format table captions in 8-point regular font and centre them. Use Roman numerals for table numbers without a dash or hyphen between the number and caption.</li>
<li>Format references in 8-point font using the prescribed format, with the reference number followed by a tab and the reference details.</li>

            </ul>

