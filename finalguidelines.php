            <ul>
             <li>For papers in which all authors are employed by the US government, the copyright notice is: U.S. Government work not protected by U.S. copyright </li>
<li>For papers in which all authors are employed by a Crown government (UK, Canada, and Australia), the copyright notice is: 979-8-3315-4613-7/26/$31.00 ©2026 Crown </li>
<li>For papers in which all authors are employed by the European Union, the copyright notice is: 979-8-3315-4613-7/26/$31.00 ©2026 European Union </li>
<li>For all other papers the copyright notice is: 979-8-3315-4613-7/26/$31.00 ©2026 IEEE</li>
            </ul>
            
    <h4 class="text-dark text-justify">Step 3: Complete the IEEE PDF eXpress Check</h4>
    
    <ul>
    <li>Access the IEEE PDF eXpress website and log in to the portal.</li>
<li>Conference ID: 66375X</li>
<li>New users must register; existing users may use their current login credentials.</li>
<li>For each conference paper, select “Create New Title.”</li>
<li>Enter identifying information for the paper. The paper title is recommended but not mandatory.</li>
<li>Select “Submit PDF for Checking” or “Submit Source Files for Conversion.”</li>
<li>Select the platform and source-file type, if applicable, browse to the file, and select “Upload File.”</li>
<li>You will receive online and email confirmation after the upload.</li>
<li>If you submitted a PDF for checking, review the result shown in the email. The PDF must pass the IEEE PDF eXpress compatibility test. Repeat the process until the file passes.</li>

    </ul>


<h4 class="text-dark text-justify">Step 4: Submit the Camera-Ready Paper</h4>
<p class="text-justify">
Submit the camera-ready paper through the CMT author console after it has passed the IEEE PDF eXpress check. Before uploading to CMT, rename the checked PDF to PID_firstauthorlastname, where PID represents the CMT paper ID (eg: 44_Singh.pdf).Also upload the doc file of the paper (eg: 44_Singh.doc). Retain the original paper title in the final manuscript. The author list and author order from the original submission must not be changed in the final manuscript.</p>




<h4 class="text-dark text-justify">Step 5: Submit the IEEE e-Copyright Form</h4>
<p class="text-justify">After uploading the camera-ready paper, which must have passed the IEEE PDF eXpress check, select “Submit IEEE Copyright Form” to access the IEEE e-Copyright Form submission page in CMT. The corresponding author may complete the copyright forms on behalf of all authors. After completing the form on the IEEE website, download the completed form and upload it to CMT.</p>

